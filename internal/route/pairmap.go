package route

// Exact pair table (M3, T4b): which (src content, dst content) pairs
// actually carry data under routing s = JCH(h, S), d = JCH(h, D).
//
// IMPORTANT (empirics 27.09, pairmap_test.go): JCH from cdbhash.c is NOT monotonic in h
// (the uint64 product carry in the key_m formula), so the "interval"
// method is impossible; the exact table is built by sweeping the domain h ∈ [0, 2^32).
//
// The consistency property (arXiv:1406.2294, confirmed by sweeping the ENTIRE domain
// for (S,D) ∈ {2,4,6,8}^2, 0 violations): D > S ⇒ d >= s; D < S ⇒ d <= s;
// S == D ⇒ d = s. This is an instant admissible (superset) bound that
// is enough for pipe selection; the exact table (fewer extra pipes) is
// PairMap.
//
// Cost of the exact sweep: ~20-50 s for ONE (S,D) pair (8 workers, 27.09)
// — NOT "~seconds" as plan M3 assumed. Therefore:
//   - built-in exact tables for realistic GP6 counts (2,4,6,8) —
//     pairmap_table.go, generated by sweeping the whole domain;
//   - for other S/D — PairMap does a full parallel sweep (memoization);
//     the calling code must account for this taking ~tens of seconds, and either run
//     it in the background, or fall back to PairBounds (instant superset).

import (
	"sort"
	"sync"
)

// PairBounds — instant (O(1)) admissible bound: the range of d for a given s.
// D > S:  d ∈ [s, D-1] (all d >= s).
// D < S:  d ∈ [0, s] (all d <= s).
// S == D: d = s.
func PairBounds(s, S, D int32) (lo, hi int32) {
	switch {
	case D > S:
		return s, D - 1
	case D < S:
		return 0, s
	default:
		return s, s
	}
}

// PairMap — the exact set of reachable pairs (s → sorted list of d):
// {(JCH(h,S), JCH(h,D)) : h ∈ [0, 2^32)}.
//
// Source order:
//  1. S == D — identity s->s (no computation);
//  2. the built-in table (pairmap_table.go, {2,4,6,8}) — instant;
//  3. memoization of a previous computation;
//  4. full parallel sweep (~20-50 s on 8 cores) — for other S/D.
func PairMap(S, D int32) map[int32][]int32 {
	if S < 1 || D < 1 {
		return map[int32][]int32{}
	}
	if S == D {
		m := make(map[int32][]int32, S)
		for s := int32(0); s < S; s++ {
			m[s] = []int32{s}
		}
		return m
	}
	if m, ok := goldenPairMap[S]; ok {
		if dm, ok := m[D]; ok {
			return dm
		}
	}
	return pairMapBruteForce(S, D)
}

// PairCount — the number of reachable (s,d) pairs for (S,D): S==D -> S; S,D>=1 ->
// len(PairMap); otherwise 0.
func PairCount(S, D int32) int {
	if S < 1 || D < 1 {
		return 0
	}
	if S == D {
		return int(S)
	}
	n := 0
	for _, ds := range PairMap(S, D) {
		n += len(ds)
	}
	return n
}

var (
	pairMapMu sync.Mutex
	pairMapM  = map[[2]int32]map[int32][]int32{}
)

// pairMapBruteForce — full sweep of h ∈ [0, 2^32), in parallel (8 workers).
// EXPENSIVE (~20-50 s): memoized, but the calling code must understand
// the cost and not run it synchronously on the critical path.
func pairMapBruteForce(S, D int32) map[int32][]int32 {
	key := [2]int32{S, D}
	pairMapMu.Lock()
	if m, ok := pairMapM[key]; ok {
		pairMapMu.Unlock()
		return m
	}
	pairMapMu.Unlock()

	const workers = 8
	// Each worker writes to its OWN table (separate backing arrays —
	// race-free), then an OR merge. A shared seen is forbidden: concurrent writes
	// into one array = data race (checked with -race).
	local := make([][][]bool, workers)
	for w := range local {
		local[w] = make([][]bool, S)
		for i := range local[w] {
			local[w][i] = make([]bool, D)
		}
	}
	var wg sync.WaitGroup
	per := (1 << 32) / uint64(workers)
	for wk := 0; wk < workers; wk++ {
		lo := uint64(wk) * per
		hi := lo + per
		if wk == workers-1 {
			hi = 1 << 32
		}
		wg.Add(1)
		go func(wk int, lo, hi uint64) {
			defer wg.Done()
			sweepPairDomain(lo, hi, S, D, local[wk])
		}(wk, lo, hi)
	}
	wg.Wait()

	m := mergeSeen(local, S, D)
	pairMapMu.Lock()
	pairMapM[key] = m
	pairMapMu.Unlock()
	return m
}

// sweepPairDomain — one worker's share of the h-domain [lo, hi): marks the
// (s,d) pairs it sees. Split out of pairMapBruteForce so the sweep and the
// merge are unit-testable on small domains (the full 2^32 sweep stays in
// the `heavy` tag).
func sweepPairDomain(lo, hi uint64, S, D int32, seen [][]bool) {
	for h := lo; h < hi; h++ {
		seen[JumpConsistentHash(h, S)][JumpConsistentHash(h, D)] = true
	}
}

// mergeSeen — OR-merge of the per-worker seen tables into the final
// (s -> sorted [d...]) map.
func mergeSeen(local [][][]bool, S, D int32) map[int32][]int32 {
	seen := local[0]
	for w := 1; w < len(local); w++ {
		for s := int32(0); s < S; s++ {
			for d := int32(0); d < D; d++ {
				if local[w][s][d] {
					seen[s][d] = true
				}
			}
		}
	}
	m := make(map[int32][]int32, S)
	for s := int32(0); s < S; s++ {
		for d := int32(0); d < D; d++ {
			if seen[s][d] {
				m[s] = append(m[s], d)
			}
		}
		sort.Slice(m[s], func(i, j int) bool { return m[s][i] < m[s][j] })
	}
	return m
}
