	numSegs := int32(2)
	mismatches := 0
	for id, seg := range livePlacement {
		if got := RouteInt4(id, numSegs); got != seg {
			if mismatches < 10 {
				t.Errorf("id=%d: computed=%d actual=%d", id, got, seg)
			}
			mismatches++
		}
	}
